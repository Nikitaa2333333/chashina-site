// Образование и практика Оксаны. Вынесено из index.astro, чтобы данные не
// раздваивались между рабочей версией блока (рельсы на главной) и пробной
// (аккордеон на /cv-2/): правка состава должна доезжать в обе сразу.
//
// СОСТАВ И ФОРМУЛИРОВКИ — ИЗ АНКЕТЫ ОКСАНЫ (скрины из сервиса записи, 21.09),
// но НАЗВАНИЯ ВУЗОВ ДЕРЖИМ СОКРАЩЁННЫМИ. Разворачивали до полных
// («Московский государственный медико-стоматологический университет
// Министерства здравоохранения РФ») — запись занимала по 100 знаков и
// вытягивала рельс в простыню, читать стало тяжелее, чем до правки.
// Сокращения тут официальные, а не придуманные: так вуз называет себя сам.
// Полные наименования есть в анкете Оксаны — если понадобится юридически
// точная формулировка, брать оттуда.
//
// В пояснениях по той же причине убрана канцелярская связка «по специальности»
// / «по курсу»: смысл она не несёт, а места занимает строку. Вид документа
// (ординатура, интернатура, переподготовка, повышение квалификации,
// сертификат) сохранён — он и отличает записи друг от друга.
// Приписки «Год выдачи диплома — 2004» не переносим: этот год уже стоит
// подписью самой записи, вторым упоминанием он только удваивает цифру.

