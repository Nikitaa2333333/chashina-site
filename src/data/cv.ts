/** Подпись годов: точечное событие — один год, текущее место работы — «сейчас». */
export const cvYears = (o: Pick<CvEntry, 'from' | 'to' | 'now'>) =>
  o.now ? `${o.from} — сейчас` : o.from === o.to ? `${o.from}` : `${o.from}–${o.to}`;

/** Охват группы для подзаголовка: «1997–2013», «2004 — сейчас». */
export const cvSpan = (list: CvEntry[]) => {
  const from = Math.min(...list.map((o) => o.from));
  const last = list[list.length - 1];
  return last?.now ? `${from} — сейчас` : `${from}–${Math.max(...list.map((o) => o.to))}`;
};
