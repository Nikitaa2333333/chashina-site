// ============================================================
// Типографика: висячие предлоги/союзы.
// Короткое слово (предлог, союз, 1–2 буквы) не должно оставаться в конце
// строки — приклеиваем его к следующему слову неразрывным пробелом (U+00A0).
// Переводы строк (\n, разбивка абзацев) НЕ трогаем — клеим только пробелы.
// ============================================================

// GOTCHA: nbsp задаём через fromCharCode, НЕ литеральным символом —
// сборщик (Vite/esbuild) нормализует литеральный U+00A0 обратно в обычный
// пробел, и склейка становится невидимой.
const NBSP = String.fromCharCode(160);

// GOTCHA: оба паттерна — regex-ЛИТЕРАЛЫ, а не new RegExp(`...\s...`):
// в template literal экранирование \s ломается и класс перестаёт ловить пробел.
// Слева — разделитель (начало, пробел/таб, скобка, кавычка, тире).
// Справа — один+ ОБЫЧНЫЙ пробел (не \s, чтобы не съесть перенос строки).
const RE_SHORT = /(?<=^|[ \t(«„"—–-])([A-Za-zА-Яа-яЁё]{1,2}) +/g;
const RE_LONG = /(?<=^|[ \t(«„"—–-])(для|что|как|или|при|под|над|без|про|это|так|где|чем|тем|уже|его|её|они|оно|она) +/gi;

export function typo(input: string): string {
  if (!input) return input;
  return input.replace(RE_SHORT, `$1${NBSP}`).replace(RE_LONG, `$1${NBSP}`);
}
